using System.Numerics;
using Assimp;
using SharpGLTF.Geometry;
using SharpGLTF.Geometry.VertexTypes;
using SharpGLTF.Materials;
using SharpGLTF.Scenes;

namespace MindAttic.AssetForge.Mesh;

/// <summary>
/// Builds a glTF <see cref="SceneBuilder"/> directly from an already-normalized (vertices baked, node
/// transforms flattened to identity by <see cref="MeshNormalizer.NormalizeScene"/>) AssimpNet <see
/// cref="Scene"/>, then saves it via SharpGLTF's own exporter -- bypassing AssimpNet's own "gltf2" exporter
/// entirely. That exporter was found to write structurally invalid accessor data: SharpGLTF's own loader
/// rejects its output as malformed ("Accessor[n] ... out of bounds ... generated by assimp") on real
/// production meshes with zero textures, animations or skins -- not a symptom of any specific content, a
/// bug in the exporter itself. Confirmed on UnitySolarSystem's 5 ship .glb files (already shipped, visually
/// fine because Unity's glTFast importer tolerates the malformed data) and on UnityEve's 3 weapon props.
/// </summary>
internal static class AssimpGltfWriter
{
    public static string Save(Scene scene, string outputPath)
    {
        var sceneBuilder = new SceneBuilder();
        var materials = new MaterialBuilder[scene.MaterialCount];
        for (var i = 0; i < scene.MaterialCount; i++) materials[i] = BuildMaterial(scene.Materials[i], i);

        foreach (var mesh in scene.Meshes)
        {
            var material = mesh.MaterialIndex >= 0 && mesh.MaterialIndex < materials.Length
                ? materials[mesh.MaterialIndex]
                : new MaterialBuilder("default");
            var meshBuilder = VertexBuilder<VertexPositionNormal, VertexTexture1, VertexEmpty>.CreateCompatibleMesh(mesh.Name ?? "mesh");
            var prim = meshBuilder.UsePrimitive(material);

            var hasUv = mesh.HasTextureCoords(0);
            foreach (var face in mesh.Faces)
            {
                if (face.IndexCount != 3) continue; // Triangulate was requested on import; anything else is degenerate.
                var v0 = BuildVertex(mesh, face.Indices[0], hasUv);
                var v1 = BuildVertex(mesh, face.Indices[1], hasUv);
                var v2 = BuildVertex(mesh, face.Indices[2], hasUv);
                prim.AddTriangle(v0, v1, v2);
            }

            sceneBuilder.AddRigidMesh(meshBuilder, System.Numerics.Matrix4x4.Identity);
        }

        var directory = Path.GetDirectoryName(Path.GetFullPath(outputPath));
        if (!string.IsNullOrEmpty(directory)) Directory.CreateDirectory(directory);

        var model = sceneBuilder.ToGltf2();
        if (string.Equals(Path.GetExtension(outputPath), ".glb", StringComparison.OrdinalIgnoreCase))
            model.SaveGLB(outputPath);
        else
            model.SaveGLTF(outputPath);
        return outputPath;
    }

    private static VertexBuilder<VertexPositionNormal, VertexTexture1, VertexEmpty> BuildVertex(Assimp.Mesh mesh, int index, bool hasUv)
    {
        var p = mesh.Vertices[index];
        var position = new Vector3(p.X, p.Y, p.Z);
        var n = mesh.HasNormals ? mesh.Normals[index] : new Vector3D(0, 1, 0);
        var normal = Vector3.Normalize(new Vector3(n.X, n.Y, n.Z) is { } v && v != Vector3.Zero ? v : Vector3.UnitY);
        var uv = Vector2.Zero;
        if (hasUv)
        {
            var t = mesh.TextureCoordinateChannels[0][index];
            uv = new Vector2(t.X, 1f - t.Y); // glTF/SharpGLTF V is flipped vs. Assimp/FBX-space V.
        }
        return new VertexBuilder<VertexPositionNormal, VertexTexture1, VertexEmpty>(
            new VertexPositionNormal(position, normal), new VertexTexture1(uv));
    }

    private static MaterialBuilder BuildMaterial(Material mat, int index)
    {
        var name = string.IsNullOrEmpty(mat.Name) ? $"material_{index}" : mat.Name;
        var color = mat.HasColorDiffuse
            ? new Vector4(mat.ColorDiffuse.R, mat.ColorDiffuse.G, mat.ColorDiffuse.B, mat.HasOpacity ? mat.Opacity : 1f)
            : new Vector4(0.8f, 0.8f, 0.8f, 1f);
        return new MaterialBuilder(name)
            .WithMetallicRoughnessShader()
            .WithChannelParam(KnownChannel.BaseColor, KnownProperty.RGBA, color)
            .WithChannelParam(KnownChannel.MetallicRoughness, KnownProperty.MetallicFactor, 0f)
            .WithChannelParam(KnownChannel.MetallicRoughness, KnownProperty.RoughnessFactor, 0.9f);
    }
}
